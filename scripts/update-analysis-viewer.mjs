// Rebuild the published Phémios component without writing into its checkout.
import { cp, mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import ts from "typescript";

const source = resolve(process.argv[2] || "../phemios");
const destination = resolve(import.meta.dirname, "../site/vendor/phemios-analysis");
const git = (...args) => execFileSync("git", ["-C", source, ...args], { encoding: "utf8" }).trim();
if (git("status", "--porcelain"))
  throw new Error("Use a clean Phémios checkout for traceable assets.");
const revision = git("rev-parse", "HEAD");
const { build } = await import(
  pathToFileURL(resolve(source, "node_modules/vite/dist/node/index.js"))
);
const { default: solid } = await import(
  pathToFileURL(resolve(source, "node_modules/vite-plugin-solid/dist/esm/index.mjs"))
);
await mkdir(destination, { recursive: true });
// Publish the corresponding source alongside the bundle, independently of upstream availability.
execFileSync("git", [
  "-C",
  source,
  "archive",
  "--format=tar.gz",
  "--output=" + resolve(destination, "source.tar.gz"),
  revision,
  "LICENSE",
  "package.json",
  "package-lock.json",
  "vite.analysis.config.ts",
  "src/analysis-report",
  "src/components/Icon.tsx",
  "src/components/icon-symbols.ts",
  "src/i18n/en.json",
]);
await build({
  root: source,
  configFile: false,
  envDir: false,
  envPrefix: [],
  publicDir: false,
  cacheDir: resolve(destination, ".cache"),
  plugins: [solid()],
  build: {
    outDir: destination,
    emptyOutDir: false,
    target: "es2022",
    lib: {
      entry: resolve(source, "src/analysis-report/index.tsx"),
      formats: ["es"],
      fileName: "flac-analysis-report",
      cssFileName: "flac-analysis-report",
    },
  },
});
const bundle = await readFile(resolve(destination, "flac-analysis-report.js"), "utf8");
const literals = new Set();
const syntax = ts.createSourceFile(
  "report.js",
  bundle,
  ts.ScriptTarget.Latest,
  true,
  ts.ScriptKind.JS,
);
function collect(node) {
  if (ts.isStringLiteralLike(node)) literals.add(node.text);
  ts.forEachChild(node, collect);
}
collect(syntax);
const catalogue = JSON.parse(await readFile(resolve(source, "src/i18n/en.json"), "utf8"));
const translations = Object.fromEntries(
  Object.entries(catalogue).filter(([key]) => literals.has(key)),
);
await writeFile(
  resolve(destination, "english.js"),
  `// Phémios report translations, MPL-2.0. Generated by update-analysis-viewer.mjs.\nexport default ${JSON.stringify(translations, null, 2)};\n`,
);
await cp(resolve(source, "LICENSE"), resolve(destination, "LICENSE"));
const licenses = await Promise.all(
  ["solid-js", "lucide-solid"].map(
    async (name) =>
      `${name}\n${await readFile(resolve(source, "node_modules", name, "LICENSE"), "utf8")}`,
  ),
);
await writeFile(resolve(destination, "THIRD-PARTY-LICENSES.txt"), licenses.join("\n\n"));
await writeFile(
  resolve(destination, "provenance.json"),
  JSON.stringify(
    {
      repository: "https://github.com/craft-and-code/phemios",
      revision,
      source: `https://github.com/craft-and-code/phemios/tree/${revision}/src/analysis-report`,
      license: "MPL-2.0",
      sha256: createHash("sha256").update(bundle).digest("hex"),
    },
    null,
    2,
  ) + "\n",
);
console.log(
  `Vendored Phémios ${revision}; ${Object.keys(translations).length} report translations.`,
);
